import { Image } from 'expo-image';
import * as WebBrowser from 'expo-web-browser';
import { useEffect, useState } from 'react';
import { ActivityIndicator, View } from 'react-native';

import { AppText } from '@/components/app-text';
import { Badge } from '@/components/badge';
import { Button } from '@/components/button';
import { Card } from '@/components/card';
import { confirmAsync } from '@/components/confirm';
import { Notice } from '@/components/notice';
import type { ProposalKey } from '@/domain/design';
import type { Project, ProposalVersion } from '@/domain/project';
import { ApiError } from '@/services/api-client';
import { refreshWorld, startWorld } from '@/services/design-service';
import { useAppStore } from '@/stores/app-store';
import { radius, spacing, useColors } from '@/theme';

const POLL_MS = 15_000;

/**
 * Optional immersive 3D: a navigable world generated by World Labs (Marble) from the
 * proposal image. Clearly marked as optional and only offered when configured.
 */
export function WorldCard({ project, proposalKey, version }: { project: Project; proposalKey: ProposalKey; version: ProposalVersion | null }) {
  const colors = useColors();
  const available = useAppStore((s) => !!s.health?.world.available);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const world = project.world;

  useEffect(() => {
    if (world?.status !== 'running') return;
    const timer = setInterval(() => {
      refreshWorld(project.id).catch(() => {});
    }, POLL_MS);
    refreshWorld(project.id).catch(() => {});
    return () => clearInterval(timer);
  }, [project.id, world?.status]);

  async function start() {
    const ok = await confirmAsync(
      'Gerar mundo 3D imersivo?',
      'A imagem da proposta será enviada ao serviço World Labs, que cria um ambiente 3D navegável em cerca de 5 minutos. O resultado fica hospedado pela World Labs e pode ser aberto por quem tiver o link. Esse serviço é cobrado por uso na conta configurada no servidor.',
      'Gerar',
    );
    if (!ok) return;
    setBusy(true);
    setError(null);
    try {
      await startWorld(project.id, proposalKey);
    } catch (e) {
      setError(e instanceof ApiError || e instanceof Error ? e.message : 'Não foi possível iniciar.');
    } finally {
      setBusy(false);
    }
  }

  if (!available) {
    return (
      <Card tone="muted" testID="world-card">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: spacing.sm }}>
          <AppText variant="headline" style={{ flex: 1 }}>
            3D imersivo com IA
          </AppText>
          <Badge label="Indisponível" />
        </View>
        <AppText variant="footnote" tone="secondary">
          Recurso opcional: gera um ambiente 3D fotorrealista e navegável a partir da imagem da proposta (World Labs Marble). Indisponível porque o servidor do app não tem este serviço configurado.
        </AppText>
      </Card>
    );
  }

  return (
    <Card testID="world-card">
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: spacing.sm }}>
        <AppText variant="headline" style={{ flex: 1 }}>
          3D imersivo com IA
        </AppText>
        <Badge label="World Labs" tone="info" />
      </View>

      {world?.status === 'running' || world?.status === 'pending' ? (
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: spacing.md }}>
          <ActivityIndicator color={colors.primary} />
          <View style={{ flex: 1 }}>
            <AppText variant="callout">Gerando o mundo 3D… (cerca de 5 minutos)</AppText>
            {world.progress ? (
              <AppText variant="footnote" tone="secondary">
                {world.progress}
              </AppText>
            ) : null}
          </View>
        </View>
      ) : world?.status === 'succeeded' && world.viewerUrl ? (
        <View style={{ gap: spacing.md }}>
          {world.thumbnailUrl ? (
            <Image source={{ uri: world.thumbnailUrl }} style={{ width: '100%', aspectRatio: 16 / 9, borderRadius: radius.md }} contentFit="cover" accessibilityLabel="Prévia do mundo 3D" />
          ) : null}
          <AppText variant="footnote" tone="secondary">
            Gerado a partir da proposta {world.proposalKey} (versão {world.proposalVersion}). Abre no visualizador da World Labs.
          </AppText>
          <Button title="Abrir mundo 3D imersivo" icon="external" onPress={() => WebBrowser.openBrowserAsync(world.viewerUrl!)} testID="open-world" />
        </View>
      ) : (
        <View style={{ gap: spacing.md }}>
          {world?.status === 'failed' ? <Notice tone="danger">{world.error ?? 'A geração falhou.'}</Notice> : null}
          <AppText variant="footnote" tone="secondary">
            Cria um ambiente 3D navegável e fotorrealista a partir da imagem da proposta. É uma reconstrução aproximada: áreas fora do campo da foto são completadas pela IA.
          </AppText>
          {version?.image ? (
            <Button title="Gerar mundo 3D imersivo" icon="cube" variant="secondary" loading={busy} onPress={start} testID="start-world" />
          ) : (
            <Notice tone="info">Disponível quando a proposta escolhida tiver uma imagem gerada por IA.</Notice>
          )}
        </View>
      )}
      {error ? <Notice tone="danger">{error}</Notice> : null}
    </Card>
  );
}
