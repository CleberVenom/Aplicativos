import { create } from 'zustand';

import type { HealthResponse } from '@/domain/api';
import { ApiError, fetchHealth } from '@/services/api-client';
import { localStore } from '@/services/storage/local-store';
import { DEFAULT_SETTINGS, type AppSettings } from '@/services/storage/types';

export type HealthStatus = 'idle' | 'checking' | 'online' | 'offline' | 'no_server';

type AppState = {
  settings: AppSettings;
  settingsLoaded: boolean;
  health: HealthResponse | null;
  healthStatus: HealthStatus;
  healthError: string | null;
  loadSettings: () => Promise<void>;
  updateSettings: (patch: Partial<AppSettings>) => Promise<void>;
  checkHealth: () => Promise<HealthResponse | null>;
};

export const useAppStore = create<AppState>((set, get) => ({
  settings: DEFAULT_SETTINGS,
  settingsLoaded: false,
  health: null,
  healthStatus: 'idle',
  healthError: null,

  async loadSettings() {
    if (get().settingsLoaded) return;
    const settings = await localStore.getSettings().catch(() => DEFAULT_SETTINGS);
    set({ settings, settingsLoaded: true });
  },

  async updateSettings(patch) {
    const settings = { ...get().settings, ...patch };
    set({ settings });
    await localStore.setSettings(settings);
  },

  async checkHealth() {
    set({ healthStatus: 'checking', healthError: null });
    try {
      const health = await fetchHealth();
      set({ health, healthStatus: 'online' });
      return health;
    } catch (error) {
      const noServer = error instanceof ApiError && error.code === 'no_server';
      set({
        health: null,
        healthStatus: noServer ? 'no_server' : 'offline',
        healthError: error instanceof Error ? error.message : 'Servidor indisponível.',
      });
      return null;
    }
  },
}));

/** True when proposals can be generated by the real AI (server online + key configured). */
export function selectAiAvailable(state: Pick<AppState, 'health' | 'healthStatus' | 'settings'>) {
  return state.healthStatus === 'online' && !!state.health?.analysis.available && !state.settings.preferDemo;
}
