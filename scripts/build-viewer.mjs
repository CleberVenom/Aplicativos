/**
 * Bundles the three.js room viewer (src/features/viewer3d/engine) into a single,
 * self-contained HTML page and writes it as a TypeScript string module. The page is
 * loaded by a WebView (native) or an iframe (web) and works offline.
 *
 *   npm run build:viewer
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src/features/viewer3d/engine/main.ts');
const out = join(root, 'src/features/viewer3d/viewer-html.generated.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  minify: true,
  format: 'iife',
  // Android System WebView (Chromium) and iOS 15+ WKWebView support ES2020.
  target: ['es2020'],
  write: false,
  legalComments: 'none',
  tsconfig: join(root, 'tsconfig.json'),
  logLevel: 'warning',
});

const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html>
<html lang="pt-BR">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
<style>
html,body{margin:0;height:100%;overflow:hidden;background:#EDE7DF;touch-action:none;-webkit-user-select:none;user-select:none;-webkit-tap-highlight-color:transparent}
#app{position:fixed;inset:0}
canvas{display:block;touch-action:none}
#label{display:none;position:fixed;left:12px;bottom:12px;max-width:calc(100% - 24px);padding:6px 12px;border-radius:999px;background:rgba(20,16,12,.75);color:#fff;font:600 13px -apple-system,system-ui,Roboto,sans-serif;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
.error{font:15px -apple-system,system-ui,Roboto,sans-serif;color:#5F554C;padding:24px;text-align:center}
</style>
</head>
<body>
<div id="app"></div>
<div id="label"></div>
<script>${js}</script>
</body>
</html>`;

const banner = `/* eslint-disable */
// GENERATED by scripts/build-viewer.mjs from src/features/viewer3d/engine — do not edit by hand.
// Contains three.js (MIT License, Copyright © 2010-2026 three.js authors).
`;
writeFileSync(out, `${banner}export const VIEWER_HTML: string = ${JSON.stringify(html)};\n`);
console.log(`viewer HTML: ${(html.length / 1024).toFixed(0)} KB -> ${out}`);
